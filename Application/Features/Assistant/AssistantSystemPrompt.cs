            • دفع مخالفة مرورية — وزارة النقل
            • تجديد رخصة القيادة — وزارة النقل (خدمة تحتاج حضوراً/موعداً)
            • دفع فاتورة الكهرباء
        - كل خدمة لها أحد نوعين فقط:
